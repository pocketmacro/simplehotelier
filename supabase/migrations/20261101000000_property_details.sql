-- SimpleHotelier — full property profile (address, contact, socials, description,
-- star rating, notification emails, age/inventory/front-desk settings, tax number).
-- Shown in Settings and on the public booking page. All additive and nullable.
alter table public.tenants
  add column if not exists address_line1 text,
  add column if not exists address_line2 text,
  add column if not exists postcode text,
  add column if not exists city text,
  add column if not exists state text,
  add column if not exists country text,
  add column if not exists contact_phone text,
  add column if not exists website_url text,
  add column if not exists facebook_url text,
  add column if not exists instagram_url text,
  add column if not exists twitter_url text,
  add column if not exists youtube_url text,
  add column if not exists description text,
  add column if not exists star_rated boolean not null default false,
  add column if not exists star_count int,
  add column if not exists max_child_age int,
  add column if not exists max_infant_age int,
  add column if not exists min_room_rate_cents int,
  add column if not exists weekend_starts text not null default 'saturday',
  add column if not exists allow_decimals boolean not null default true,
  add column if not exists booking_email text,
  add column if not exists booking_cc_email text,
  add column if not exists enquiry_email text,
  add column if not exists availability_email text,
  add column if not exists gdpr_consent boolean not null default false,
  add column if not exists tax_number text;
